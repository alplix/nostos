"""Generates src/nostos_kernel_cl.inc: the OpenCL C source of the Nostos kernel as a C string literal
(an OpenCL prelude + src/nostos_kernel_body.h, the same device code the CUDA backend compiles).
Run after editing nostos_kernel_body.h:  python scripts/embed_kernel.py"""
import os

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "src")
prelude = """#pragma OPENCL EXTENSION cl_khr_fp64 : enable
#pragma OPENCL FP_CONTRACT OFF
#define NG_GLOBAL __global
#define NG_DEVICE
#define NG_KERNEL __kernel
#define NG_TID ((int)get_global_id(0))
"""
body = open(os.path.join(src, "nostos_kernel_body.h"), encoding="utf-8").read()
lines = (prelude + body).splitlines()
out = ["// GENERATED by scripts/embed_kernel.py from nostos_kernel_body.h -- do not edit by hand.",
       "static const char *kNostosKernelCL ="]
for ln in lines:
    out.append('    "' + ln.replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
out[-1] += ";"
open(os.path.join(src, "nostos_kernel_cl.inc"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote src/nostos_kernel_cl.inc,", len(lines), "lines")
